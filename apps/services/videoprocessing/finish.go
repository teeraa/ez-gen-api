package videoprocessing

import (
	_ "embed"
	"fmt"
	"os"
	"path/filepath"
)

// FinishFilm grades the merged picture like live-action footage printed to film, the
// standard post pass for generated video: a film-print look LUT (lower saturation, less
// teal, print tone curve with a toe and a highlight shoulder, warm highlights), halation
// around bright highlights, a slight optical softening of the over-sharp AI edge, and
// moving luma grain. It runs before image and text layers, so titles stay clean.
const FinishFilm = "film"

// filmPrintLUT is our own 33-point Rec.709 look, generated by scripts/film_look/make_lut.py
// (already blended at 75% with the identity).
//
//go:embed looks/film_print.cube
var filmPrintLUT []byte

const (
	// filmHalation is the screen opacity of the blurred red-orange highlight glow.
	filmHalation = 0.22
	// filmGrain is FFmpeg noise strength on luma only, re-drawn every frame.
	filmGrain = 9
)

func validFinish(finish string) bool { return finish == "" || finish == FinishFilm }

// finishParts writes the look's LUT into dir and returns filter graph parts that read label
// in and write label out at w×h. The halation branch is blurred at quarter size: same glow,
// a fraction of the cost.
func finishParts(finish, in, out, dir string, w, h int) ([]string, error) {
	if finish != FinishFilm {
		return nil, fmt.Errorf("unknown finish %q", finish)
	}
	lut := filepath.Join(dir, "film_print.cube")
	if e := os.WriteFile(lut, filmPrintLUT, 0o600); e != nil {
		return nil, e
	}
	hw, hh := max(2, w/8*2), max(2, h/8*2)
	return []string{
		fmt.Sprintf("%sformat=gbrp,lut3d=file='%s':interp=tetrahedral,split=2[fbase][fhl]", in, lut),
		fmt.Sprintf("[fhl]curves=all='0/0 0.72/0 1/1',scale=%d:%d,gblur=sigma=3,colorchannelmixer=rr=1:gg=0.35:bb=0.12,scale=%d:%d[fhalo]", hw, hh, w, h),
		fmt.Sprintf("[fbase][fhalo]blend=all_mode=screen:all_opacity=%.2f,unsharp=5:5:-0.35:5:5:0,format=yuv420p,noise=c0s=%d:c0f=t+u%s", filmHalation, filmGrain, out),
	}, nil
}
