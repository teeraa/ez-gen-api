"""Generate the film-print look as a 33-point 3D LUT (.cube, Rec.709 display in/out).

The look follows what a print-film emulation does to display-referred video:
  1. tame AI hyper-colour: global saturation down, extra on cyan/teal hues;
  2. dye crosstalk: a little of each channel bleeds into the others (softer colour separation);
  3. print tone curve per channel: S-curve with a toe and a highlight shoulder, blacks dense but
     not crushed, whites rolled off below clipping; shadows lean slightly cool, highlights warm;
  4. the whole look is blended with the identity at STRENGTH (colourists run print LUTs at 60-80%).

The LUT is our own (no third-party print emulation is redistributed). Regenerate with:
  python3 scripts/film_look/make_lut.py apps/services/videoprocessing/looks/film_print.cube
"""
import sys
import numpy as np

N = 33
STRENGTH = 0.75
SAT = 0.86            # global saturation
TEAL_SAT = 0.72       # extra factor on cyan/teal hues (150-215 deg)
CONTRAST = 2.1        # tanh steepness of the print S-curve
# per-channel print curve: (pivot, black, white)
CURVE = {0: (0.42, 0.020, 0.975), 1: (0.43, 0.024, 0.962), 2: (0.45, 0.032, 0.930)}
CROSSTALK = np.array([[0.93, 0.05, 0.02],
                      [0.03, 0.94, 0.03],
                      [0.02, 0.06, 0.92]])
LUMA = np.array([0.2126, 0.7152, 0.0722])


def hue_deg(rgb):
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mx, mn = rgb.max(-1), rgb.min(-1)
    d = np.where(mx - mn == 0, 1e-9, mx - mn)
    h = np.where(mx == r, ((g - b) / d) % 6, np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4))
    return h * 60.0


def print_curve(x, pivot, black, white):
    s = lambda v: np.tanh(CONTRAST * (v - pivot))
    y = (s(x) - s(0.0)) / (s(1.0) - s(0.0))
    return black + (white - black) * y


def look(rgb):
    y = (rgb * LUMA).sum(-1, keepdims=True)
    h = hue_deg(rgb)[..., None]
    w = np.clip(1 - np.abs(h - 182.5) / 32.5, 0, 1)  # 1 at teal, 0 outside 150-215
    sat = SAT * (1 - (1 - TEAL_SAT) * w)
    out = y + (rgb - y) * sat
    out = np.clip(out @ CROSSTALK.T, 0, 1)
    for c, (p, b, wt) in CURVE.items():
        out[..., c] = print_curve(out[..., c], p, b, wt)
    out = rgb + (out - rgb) * STRENGTH
    return np.clip(out, 0, 1)


def main(path):
    g = np.linspace(0, 1, N)
    # .cube order: red changes fastest, then green, then blue.
    b, gg, r = np.meshgrid(g, g, g, indexing="ij")
    rgb = np.stack([r, gg, b], -1).reshape(-1, 3)
    out = look(rgb)
    with open(path, "w") as f:
        f.write('TITLE "EZ-Gen film print look"\n')
        f.write("# Generated by scripts/film_look/make_lut.py - Rec.709 display in, Rec.709 display out\n")
        f.write(f"LUT_3D_SIZE {N}\nDOMAIN_MIN 0.0 0.0 0.0\nDOMAIN_MAX 1.0 1.0 1.0\n")
        for v in out:
            f.write(f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "film_print.cube")
